  if (/^下一/.test(label)) return 'arrow-right';
  if (/相关内容/.test(label)) return 'link';
  if (/^使用方式$/.test(label)) return 'info';
  if (/catalog|related|search-result|file-name/.test(className)) return 'file';
  if (label==='提问') return 'send';
  if (/缩小/.test(label)) return 'minus';
  if (/放大/.test(label)) return 'plus';
  if (/复位/.test(label)) return 'reset';
  if (/已复制|复制成功|完成|已选/.test(label)) return 'check';
  if (/关闭|取消|清除引用|收起本次/.test(label)) return 'close';
  if (/复制/.test(label)) return 'copy';
  if (/新建|创建|新对话|加入列表/.test(label)) return 'plus';
